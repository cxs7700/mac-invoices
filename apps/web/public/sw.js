/*
 * Service worker for the vendor submission link (see src/lib/pwa.ts).
 *
 * Registered ONLY from the /submit/:token route. It is served from the origin
 * root, so its scope is "/" and it therefore sees the landlord app's requests
 * too — everything outside the submission flow is deliberately passed straight
 * through untouched (no respondWith), so the authenticated app is never cached
 * and can never be served stale.
 *
 * What it does cache: the built SPA shell, so an installed submission link
 * opens offline instead of showing the browser's dinosaur. Submitting still
 * needs a connection — API requests are never cached, and never queued.
 *
 * Hand-written rather than generated by vite-plugin-pwa: the plugin precaches
 * the whole app by default, which is exactly what this must not do.
 */

// Bump to invalidate every cached asset. The build hashes asset filenames, so
// stale JS is evicted by URL anyway; this covers index.html and the icons.
const CACHE = 'submit-shell-v1'

const SHELL = ['/index.html', '/icon-192.png', '/icon-512.png', '/apple-touch-icon.png']

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      // Individually, so one missing file cannot fail the whole install the way
      // addAll would.
      .then((cache) => Promise.allSettled(SHELL.map((url) => cache.add(url))))
      // Take over as soon as the new worker is ready: a vendor who reopens the
      // installed link should not be pinned to the previous deploy's shell.
      .then(() => self.skipWaiting()),
  )
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

/** Only the submission flow is cached; everything else is left to the network. */
function inScope(url) {
  return url.origin === self.location.origin && url.pathname.startsWith('/submit')
}

/** Hashed build output under /assets/, plus the icons the manifest points at. */
function isBuildAsset(url) {
  return (
    url.origin === self.location.origin &&
    (url.pathname.startsWith('/assets/') || /^\/(icon-|apple-touch-icon)/.test(url.pathname))
  )
}

self.addEventListener('fetch', (event) => {
  const { request } = event
  if (request.method !== 'GET') return

  const url = new URL(request.url)

  // Never cache the API. A cached submission list or property list would show a
  // vendor stale state, and a cached POST response is meaningless.
  if (url.pathname.startsWith('/api/')) return

  // A navigation to the submission link: network first so a live vendor always
  // gets the current build, falling back to the cached shell when offline.
  // The SPA serves index.html for every route, so the shell answers any token.
  if (request.mode === 'navigate') {
    if (!inScope(url)) return
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone()
          void caches.open(CACHE).then((cache) => cache.put('/index.html', copy))
          return response
        })
        .catch(() => caches.match('/index.html').then((hit) => hit ?? Response.error())),
    )
    return
  }

  // Hashed assets are immutable, so cache-first is safe and makes the installed
  // link open instantly; a new deploy produces new filenames, which miss and
  // fetch. Note this bundle is shared with the landlord app, so if the same
  // browser opens both, its assets get cached here too. That is harmless
  // precisely because the filenames are content-addressed — staleness is
  // impossible. The landlord's *document* and API responses are still never
  // cached, which is the part that would actually go stale.
  if (!isBuildAsset(url)) return
  event.respondWith(
    caches.match(request).then(
      (hit) =>
        hit ??
        fetch(request).then((response) => {
          if (response.ok && response.type === 'basic') {
            const copy = response.clone()
            void caches.open(CACHE).then((cache) => cache.put(request, copy))
          }
          return response
        }),
    ),
  )
})
